using Microsoft.AspNetCore.Components.Authorization;

namespace LARGA.ManagerWeb.Services;

/// <summary>
/// ANA-007 / ANA-012: turns a <see cref="ReportDocument"/> - the same tables its CSV is written
/// from - into a PDF with QuestPDF (Community license, set in Program.cs). Header: LARGA / BLM
/// Taxi, the report title, its date range, who generated it and when (Philippine time, UTC+8);
/// then each table, with peso columns as ₱1,234.00; "Page x of y" in the footer. A4 landscape,
/// since several reports are wide.
/// </summary>
public static class PdfReportRenderer
{
    private static readonly CultureInfo Numbers = CultureInfo.InvariantCulture;

    public static byte[] Render(ReportDocument report, DateTime fromDatePh, DateTime toDatePh, string generatedBy)
    {
        DateTime generatedAtPh = PhilippineTime.Now;
        string range = fromDatePh.Date == toDatePh.Date
            ? fromDatePh.ToString("MMMM d, yyyy", Numbers)
            : $"{fromDatePh.ToString("MMMM d, yyyy", Numbers)} – {toDatePh.ToString("MMMM d, yyyy", Numbers)}";

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4.Landscape());
                page.Margin(28);
                page.DefaultTextStyle(style => style.FontSize(8).FontColor(Colors.Grey.Darken4));

                page.Header().PaddingBottom(10).Column(column =>
                {
                    column.Item().Text("LARGA / BLM Taxi").SemiBold().FontSize(10).FontColor(Colors.Grey.Darken2);
                    column.Item().Text(report.Title).Bold().FontSize(16);
                    column.Item().PaddingTop(4).Text($"Date range: {range}");
                    column.Item().Text($"Generated by: {generatedBy}");
                    column.Item().Text($"Generated at: {generatedAtPh.ToString("MMMM d, yyyy h:mm tt", Numbers)} (Philippine time, UTC+8)");
                    column.Item().PaddingTop(6).LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
                });

                page.Content().Column(column =>
                {
                    column.Spacing(14);
                    foreach (ReportTable table in report.Tables)
                    {
                        column.Item().Column(section =>
                        {
                            if (!string.IsNullOrWhiteSpace(table.Heading))
                            {
                                section.Item().PaddingBottom(4).Text(table.Heading).Bold().FontSize(11);
                            }

                            if (table.Rows.Count == 0)
                            {
                                section.Item().Text("No records in this date range.").Italic().FontColor(Colors.Grey.Darken1);
                                return;
                            }

                            section.Item().Table(grid => DrawTable(grid, table));
                            section.Item().PaddingTop(3).Text($"{table.Rows.Count} record(s)").FontColor(Colors.Grey.Darken1);
                        });
                    }
                });

                page.Footer().AlignCenter().Text(text =>
                {
                    text.Span("Page ");
                    text.CurrentPageNumber();
                    text.Span(" of ");
                    text.TotalPages();
                });
            });
        }).GeneratePdf();
    }

    private static void DrawTable(TableDescriptor grid, ReportTable table)
    {
        int columns = table.Headers.Count;
        IReadOnlyList<float> widths = table.RelativeWidths is { } w && w.Count == columns
            ? w
            : Enumerable.Repeat(1f, columns).ToList();

        grid.ColumnsDefinition(definition =>
        {
            foreach (float width in widths)
            {
                definition.RelativeColumn(width);
            }
        });

        // Repeated at the top of every page the table runs onto.
        grid.Header(header =>
        {
            for (int i = 0; i < columns; i++)
            {
                IContainer cell = header.Cell().Background(Colors.Grey.Lighten3).Padding(4);
                if (table.MoneyColumns.Contains(i))
                {
                    cell = cell.AlignRight();
                }
                cell.Text(table.Headers[i]).SemiBold();
            }
        });

        foreach (object?[] row in table.Rows)
        {
            for (int i = 0; i < columns; i++)
            {
                object? value = i < row.Length ? row[i] : null;
                IContainer cell = grid.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).PaddingVertical(3).PaddingHorizontal(4);
                if (table.MoneyColumns.Contains(i))
                {
                    cell.AlignRight().Text(FormatPeso(value));
                }
                else
                {
                    cell.Text(value?.ToString() ?? string.Empty);
                }
            }
        }
    }

    /// <summary>"Generated by" for the signed-in manager: their users/{uid}.fullName and email,
    /// or just the email when the profile can't be read.</summary>
    public static async Task<string> DescribeUserAsync(AuthenticationStateProvider authState, Lazy<FirestoreDb> db)
    {
        ClaimsPrincipal user = (await authState.GetAuthenticationStateAsync()).User;
        string email = user.FindFirst(ClaimTypes.Email)?.Value ?? user.Identity?.Name ?? "Unknown user";
        string? uid = user.FindFirst(ClaimTypes.NameIdentifier)?.Value;
        if (string.IsNullOrEmpty(uid))
        {
            return email;
        }

        try
        {
            DocumentSnapshot doc = await db.Value.Collection("users").Document(uid).GetSnapshotAsync();
            string? name = doc.Exists && doc.TryGetValue("fullName", out string? fullName) ? fullName?.Trim() : null;
            return string.IsNullOrEmpty(name) ? email : $"{name} ({email})";
        }
        catch
        {
            return email;
        }
    }

    /// <summary>₱1,234.00 - amounts in Philippine pesos.</summary>
    public static string FormatPeso(object? value)
    {
        if (value is null)
        {
            return string.Empty;
        }

        try
        {
            decimal amount = Convert.ToDecimal(value, Numbers);
            return (amount < 0 ? "-₱" : "₱") + Math.Abs(amount).ToString("N2", Numbers);
        }
        catch (Exception ex) when (ex is FormatException or InvalidCastException or OverflowException)
        {
            return value.ToString() ?? string.Empty;
        }
    }
}
