"""Generates the synthetic SOS sensor traces in this folder (SensorTrace format, see
LARGA.SharedCore/Emergency/SensorTrace.cs). Run from anywhere:  python gen_sos_traces.py

Accelerometer at 50 Hz (Android SensorDelay.Game), raw m/s^2 with gravity included, GPS at 1 Hz.
Crash spikes are one sample long; the raw value is chosen so the gravity-free magnitude the
detector sees right after the GravityFilter (0.8 * (raw - gravity)) is the stated G.
The traces recorded on the emulator (emu_*.txt) are not generated here.
"""
import math
import os
import random

G = 9.80665
HZ = 50
HERE = os.path.dirname(os.path.abspath(__file__))


def write(name, comment, lines):
    with open(os.path.join(HERE, name), "w", newline="\n") as f:
        f.write(f"# {comment}\n# synthetic - generated by gen_sos_traces.py\n")
        f.write("\n".join(lines) + "\n")


def a(t, x, y, z):
    return f"a,{t:.3f},{x:.3f},{y:.3f},{z:.3f}"


def g(t, speed):
    return f"g,{t:.3f}," + ("" if speed is None else f"{speed:.2f}")


def rest(t0, t1, gravity=(0, 0, G), noise=0.05, rnd=None):
    rnd = rnd or random.Random(1)
    out, n = [], int((t1 - t0) * HZ)
    for i in range(n):
        t = t0 + i / HZ
        out.append(a(t, gravity[0] + rnd.uniform(-noise, noise),
                     gravity[1] + rnd.uniform(-noise, noise),
                     gravity[2] + rnd.uniform(-noise, noise)))
    return out


def shake(name, comment, hz, seconds, axis="x", amp=8.0):
    lines = rest(0, 1)
    n = int(seconds * HZ)
    for i in range(n):
        t = 1 + i / HZ
        v = amp * math.sin(2 * math.pi * hz * (t - 1))
        x, y, z = (v, 0, G) if axis == "x" else (0, v, G) if axis == "y" else (0, 0, G + v)
        lines.append(a(t, x, y, z))
    lines += rest(1 + seconds, 2 + seconds)
    write(name, comment, lines)


def drive(name, comment, spike_at, spike_g, speeds_after, gravity=(0, 0, G), spike_axis="z",
          speed_before=12.0, total=None):
    """Moving at speed_before (m/s) with 1 Hz fixes; one spike; then speeds_after[i] at spike+1+i s."""
    rnd = random.Random(7)
    total = total or spike_at + len(speeds_after) + 2
    lines = []
    for i in range(int(total * HZ)):
        t = i / HZ
        gx, gy, gz = gravity
        x = gx + rnd.uniform(-0.3, 0.3)
        y = gy + rnd.uniform(-0.3, 0.3)
        z = gz + rnd.uniform(-0.3, 0.3)
        if abs(t - spike_at) < 1e-6:
            raw = spike_g * G / 0.8
            if spike_axis == "x":
                x = gx + raw
            elif spike_axis == "y":
                y = gy + raw
            else:
                z = gz + raw
        lines.append(a(t, x, y, z))
    for s in range(int(total) + 1):
        if s <= spike_at:
            speed = speed_before
        else:
            k = s - int(spike_at) - 1
            speed = speeds_after[k] if k < len(speeds_after) else speeds_after[-1]
        lines.append(g(float(s) + 0.5, speed))
    write(name, comment, sorted(lines, key=lambda l: float(l.split(",")[1])))


# Hostile (SOS-008/010/011)
shake("sos008_hostile_shake_3hz.txt", "SOS-008 side-to-side shake ~3 swings/s for 3.5 s (X axis)", 3, 3.5)
shake("sos010_short_shake_2s.txt", "SOS-010 step 1: side-to-side shake for 2 s only", 3, 2.0)
shake("sos010_vertical_shake.txt", "SOS-010 step 2: up/down shake ~3/s for 3.5 s (Z axis)", 3, 3.5, axis="z")
shake("sos011_slow_sway_1hz.txt", "SOS-011 step 1: slow sway ~1 swing/s for 3.5 s", 1, 3.5)
shake("sos011_fast_vibration_8hz.txt", "SOS-011 step 2: fast vibration ~8 swings/s for 3.5 s", 8, 3.5, amp=6.0)

# Rough road (SOS-010 step 3): 120 s of mostly-vertical bumps with some sway, moving at 8-12 m/s.
rnd = random.Random(42)
lines, z_bump = [], 0.0
for i in range(120 * HZ):
    t = i / HZ
    if rnd.random() < 0.03:
        z_bump = rnd.uniform(-6, 6)       # pothole / speed bump
    z_bump *= 0.85
    lines.append(a(t, rnd.gauss(0, 1.2), rnd.gauss(0, 1.2), G + z_bump + rnd.gauss(0, 1.5)))
for s in range(121):
    lines.append(g(s + 0.5, rnd.uniform(8, 12)))
write("sos010_rough_road_120s.txt", "SOS-010 step 3: 120 s rough road, vertical bumps + lateral noise",
      sorted(lines, key=lambda l: float(l.split(",")[1])))

