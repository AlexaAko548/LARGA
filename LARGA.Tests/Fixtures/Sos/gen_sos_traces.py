drive("sos019_pothole_keeps_moving.txt", "SOS-019 5 G pothole (Z) at 20 s, keeps going at 43 km/h", 20.0, 5.0, [12.0] * 12)
drive("sos020_drop_while_parked.txt", "SOS-020 parked 20 s, phone dropped (6 G), still parked", 20.0, 6.0, [0.0] * 5, speed_before=0.0)
drive("sos021_3_9g_then_stop.txt", "SOS-021 3.9 G (Z) at 20 s, then stop", 20.0, 3.9, [0.3, 0.1, 0.0])
drive("sos021_4_1g_then_stop.txt", "SOS-021 4.1 G (Z) at 20 s, then stop", 20.0, 4.1, [0.3, 0.1, 0.0])
drive("sos022_xaxis_upright_mount.txt", "SOS-022 phone upright (gravity on Y), 4.5 G frontal impact on X, then stop",
      20.0, 4.5, [0.3, 0.1, 0.0], gravity=(0, G, 0), spike_axis="x")
drive("sos023_stop_after_12s.txt", "SOS-023 4.5 G at 20 s, keeps moving until the stop 12 s later",
      20.0, 4.5, [12.0] * 11 + [0.2, 0.1, 0.0])
